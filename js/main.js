(function () {
    'use strict';

    var THEME_KEY = 'lp-theme';
    var root = document.documentElement;

    function applyTheme(mode) {
        root.setAttribute('data-theme', mode);
        root.style.colorScheme = mode;
        document.querySelectorAll('[data-theme-toggle]').forEach(function (btn) {
            var icon = btn.querySelector('i');
            if (icon) icon.className = mode === 'dark' ? 'bi bi-sun' : 'bi bi-moon-stars';
            btn.setAttribute('aria-pressed', mode === 'dark' ? 'true' : 'false');
        });
    }

    function currentTheme() {
        var saved = null;
        try { saved = localStorage.getItem(THEME_KEY); } catch (e) {}
        if (saved) return saved;
        return window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
    }

    applyTheme(currentTheme());

    function initNav() {
        var header = document.querySelector('.site-header');
        var toggle = document.querySelector('[data-nav-toggle]');
        var links  = document.querySelector('[data-nav-links]');

        if (header) {
            var onScroll = function () { header.classList.toggle('is-scrolled', window.scrollY > 8); };
            onScroll();
            window.addEventListener('scroll', onScroll, { passive: true });
        }

        if (toggle && links) {
            toggle.addEventListener('click', function () {
                var open = links.classList.toggle('is-open');
                toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
            });
            links.querySelectorAll('a').forEach(function (a) {
                a.addEventListener('click', function () {
                    links.classList.remove('is-open');
                    toggle.setAttribute('aria-expanded', 'false');
                });
            });
            document.addEventListener('click', function (ev) {
                if (!links.classList.contains('is-open')) return;
                if (header && header.contains(ev.target)) return;
                links.classList.remove('is-open');
                toggle.setAttribute('aria-expanded', 'false');
            });
        }
    }

    function initReveals() {
        var reveals = document.querySelectorAll('.reveal');
        if (!reveals.length) return;
        if (!('IntersectionObserver' in window)) {
            reveals.forEach(function (el) { el.classList.add('is-visible'); });
            return;
        }
        var io = new IntersectionObserver(function (entries) {
            entries.forEach(function (en) {
                if (en.isIntersecting) {
                    en.target.classList.add('is-visible');
                    io.unobserve(en.target);
                }
            });
        }, { rootMargin: '-60px 0px -60px 0px', threshold: 0.05 });
        reveals.forEach(function (el) { io.observe(el); });
    }

    function initCounters() {
        var counters = document.querySelectorAll('[data-counter]');
        if (!counters.length || !('IntersectionObserver' in window)) return;

        var animate = function (el) {
            var raw = el.getAttribute('data-counter') || '';
            var match = raw.match(/^([^\d\-+.]+)?([\d.,]+)(.*)$/);
            if (!match) return;
            var prefix = match[1] || '';
            var numStr = match[2].replace(',', '.');
            var suffix = match[3] || '';
            var target = parseFloat(numStr);
            if (isNaN(target)) return;
            var decimals = (numStr.split('.')[1] || '').length;
            var start = performance.now();
            var dur = 1600;
            var ease = function (t) { return 1 - Math.pow(1 - t, 3); };
            var tick = function (now) {
                var p = Math.min((now - start) / dur, 1);
                var v = target * ease(p);
                var txt = decimals ? v.toFixed(decimals) : Math.round(v).toLocaleString();
                el.textContent = prefix + txt + suffix;
                if (p < 1) requestAnimationFrame(tick);
                else el.textContent = prefix + match[2] + suffix;
            };
            requestAnimationFrame(tick);
        };

        var io = new IntersectionObserver(function (entries) {
            entries.forEach(function (en) {
                if (en.isIntersecting) {
                    animate(en.target);
                    io.unobserve(en.target);
                }
            });
        }, { threshold: 0.35 });
        counters.forEach(function (el) { io.observe(el); });
    }

    function initMisc() {
        document.querySelectorAll('a[href^="#"]').forEach(function (a) {
            a.addEventListener('click', function (ev) {
                var id = a.getAttribute('href');
                if (!id || id === '#') return;
                var target = document.querySelector(id);
                if (!target) return;
                ev.preventDefault();
                target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                history.replaceState(null, '', id);
            });
        });

        document.querySelectorAll('[data-year]').forEach(function (el) {
            el.textContent = new Date().getFullYear();
        });

        document.querySelectorAll('form[data-validate]').forEach(function (form) {
            form.addEventListener('submit', function (ev) {
                var ok = true;
                form.querySelectorAll('input[required], textarea[required]').forEach(function (f) {
                    if (!f.value.trim()) { f.style.borderColor = '#ef4444'; ok = false; }
                    else { f.style.borderColor = ''; }
                });
                if (!ok) {
                    ev.preventDefault();
                    var btn = form.querySelector('button[type="submit"]');
                    if (btn) {
                        var orig = btn.innerHTML;
                        btn.innerHTML = 'Please fill in the required fields';
                        setTimeout(function () { btn.innerHTML = orig; }, 2200);
                    }
                }
            });
        });

        var sections = document.querySelectorAll('section[id]');
        var navLinks = document.querySelectorAll('.nav-links a[href^="#"]');
        if (sections.length && navLinks.length && 'IntersectionObserver' in window) {
            var io = new IntersectionObserver(function (entries) {
                entries.forEach(function (en) {
                    if (!en.isIntersecting) return;
                    var id = '#' + en.target.id;
                    navLinks.forEach(function (a) {
                        var on = a.getAttribute('href') === id;
                        a.style.color = on ? 'var(--text)' : '';
                        a.style.background = on ? 'color-mix(in srgb, var(--text) 5%, transparent)' : '';
                    });
                });
            }, { rootMargin: '-40% 0px -55% 0px' });
            sections.forEach(function (s) { io.observe(s); });
        }
    }

    function boot() {
        document.querySelectorAll('[data-theme-toggle]').forEach(function (btn) {
            btn.addEventListener('click', function () {
                var next = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
                try { localStorage.setItem(THEME_KEY, next); } catch (e) {}
                applyTheme(next);
            });
        });

        window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', function (ev) {
            var saved = null;
            try { saved = localStorage.getItem(THEME_KEY); } catch (er) {}
            if (!saved) applyTheme(ev.matches ? 'dark' : 'light');
        });

        initNav();
        initReveals();
        initCounters();
        initMisc();
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', boot);
    } else {
        boot();
    }
})();